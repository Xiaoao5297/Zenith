namespace lycore\entity;

use lycore\entity\behavior\attackEnemyBehavior;
use lycore\network\protocol\AddEntityPacket;
use lycore\Player;

class Silverfish extends Monster{
	const NETWORK_ID = 39;

	public $width = 0.4;
	public $length = 0.4;
	public $height = 0.3;

	public $dropExp = [5, 5];
	
	public function getName() : string{
		return "Silverfish";
	}

	public function usesPm1eGroundAi() : bool{
		return true;
	}

	public function initEntity(){
		$this->setMaxHealth(8);
		$this->addBehavior(new attackEnemyBehavior($this, [20, 21], true));
		parent::initEntity();
	}
	
	public function spawnTo(Player $player){
		$pk = new AddEntityPacket();
		$pk->eid = $this->getId();
		$pk->type = Silverfish::NETWORK_ID;
		$pk->x = $this->x;
		$pk->y = $this->y;
		$pk->z = $this->z;
		$pk->speedX = $this->motionX;
		$pk->speedY = $this->motionY;
		$pk->speedZ = $this->motionZ;
		$pk->yaw = $this->yaw;
		$pk->pitch = $this->pitch;
		$pk->metadata = $this->dataProperties;
		$player->dataPacket($pk);

		parent::spawnTo($player);
	}
}
