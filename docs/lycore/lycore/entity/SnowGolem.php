namespace lycore\entity;

use lycore\network\protocol\AddEntityPacket;
use lycore\Player;
use lycore\entity\behavior\ShootEnemyBehavior;

class SnowGolem extends Animal{
	const NETWORK_ID = 21;

	public $width = 0.3;
	public $length = 0.9;
	public $height = 2.0;
	
	public function initEntity(){
		$this->setMaxHealth(100);
		
		$this->addBehavior(new ShootEnemyBehavior($this, [32, 33, 34, 35, 36, 40, 44], "Snowball"));
		
		parent::initEntity();
	}

	public function usesPm1eGroundAi() : bool{
		return true;
	}
	
	public function getName() {
		return "Snow Golem";
	}
	
	public function getHurt(){
		return mt_rand(7, 21);
	}
	
	public function spawnTo(Player $player) {
		$pk = new AddEntityPacket();
		$pk->eid = $this->getId();
		$pk->type = self::NETWORK_ID;
		$pk->x = $this->x;
		$pk->y = $this->y;
		$pk->z = $this->z;
		$pk->speedX = $this->motionX;
		$pk->speedY = $this->motionY;
		$pk->speedZ = $this->motionZ;
		$pk->yaw = $this->yaw;
		$pk->pitch = $this->pitch;
		$pk->metadata = $this->dataProperties;
		$player->dataPacket($pk);

		parent::spawnTo($player);
	}
}
