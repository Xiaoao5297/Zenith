namespace lycore\item;


class Snowball extends Item{
	public function __construct($meta = 0, $count = 1){
		parent::__construct(self::SNOWBALL, $meta, $count, $meta === 1 ? "Ender Pearl" : "Snowball");
		if($meta === 1){
			$this->setCustomName("Ender Pearl");
		}
	}

	public function getMaxStackSize() : int {
		return 16;
	}

}
