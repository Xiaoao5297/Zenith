namespace lycore\block;

class StickyPiston extends PistonBase{
	protected $id = self::STICKY_PISTON;
	protected $sticky = true;

	public function getName() : string{
		return "Sticky Piston";
	}

	protected function createHead($face){
		$head = new PistonHead();
		$head->setFacing($face);
		$head->setSticky(true);
		return $head;
	}
}
