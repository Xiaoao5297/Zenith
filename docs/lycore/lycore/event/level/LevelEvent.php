/**
 * Level related events
 */
namespace lycore\event\level;

use lycore\event\Event;
use lycore\level\Level;

abstract class LevelEvent extends Event{
	/** @var \lycore\level\Level */
	private $level;

	/**
	 * @param Level $level
	 */
	public function __construct(Level $level){
		$this->level = $level;
	}

	/**
	 * @return \lycore\level\Level
	 */
	public function getLevel(){
		return $this->level;
	}
}