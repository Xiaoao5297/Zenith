namespace pocketmine\network\protocol\v84;

class RiderJumpPacketV84 extends DataPacketV84{
	const NETWORK_ID = InfoV84::RIDER_JUMP_PACKET;

	public $eid;
	public $jumpStrength;

	public function decode(){
		$this->eid = $this->getLong();
		$this->jumpStrength = $this->getInt();
	}

	public function encode(){
		$this->reset();
		$this->putLong($this->eid);
		$this->putInt($this->jumpStrength);
	}
}
