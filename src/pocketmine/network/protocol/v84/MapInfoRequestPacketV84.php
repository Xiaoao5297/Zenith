namespace pocketmine\network\protocol\v84;

class MapInfoRequestPacketV84 extends DataPacketV84 {

	const NETWORK_ID = InfoV84::MAP_INFO_REQUEST_PACKET;

	/** @var int */
	public $mapId;

	public function decode() {
		$this->mapId = $this->getLong();
	}

	public function encode(){
		$this->reset();
		$this->putLong($this->mapId);
	}

}