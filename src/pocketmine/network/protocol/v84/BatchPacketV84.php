namespace pocketmine\network\protocol\v84;

#include <rules/DataPacket.h>


class BatchPacketV84 extends DataPacketV84{
	const NETWORK_ID = InfoV84::BATCH_PACKET;

	public $payload;

	public function decode(){
		$size = $this->getInt();
		$this->payload = $this->get($size);
	}

	public function encode(){
		$this->reset();
		$this->putInt(strlen($this->payload));
		$this->put($this->payload);
	}

}